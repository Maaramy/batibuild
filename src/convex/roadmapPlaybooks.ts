// ── Trames ───────────────────────────────────────────────────────────────────

export interface PlaybookTask {
  id: string;
  phase: ExecutionPhaseKey;
  title: string;
  objectif: string;
  travaux: string[];
  materiaux: string[];
  mainOeuvre: string[];
  outillage: string[];
  controles: string[];
  risques: string[];
  conditions: string[];
  responsible: string;
  /** Part relative de la durée et du budget (normalisée par le moteur). */
  weight: number;
  /** Tâche dépliée pour chaque niveau réel du projet (RDC, R+1…). */
  perLevel?: boolean;
  /** Condition d'affichage selon les données du projet. */
  requires?: "multi_level" | "pool" | "exterior" | "elevator";
}

export interface DurationModel {
  minDays: number;
  daysPerM2: number;
  daysPerFloor: number;
  /** Les projets neufs sont aussi modulés par le coût au m². */
  costAdjusted: boolean;
}

export interface ExecutionPlaybook {
  key: string;
  label: string;
  executionTitle: string;
  executionDescription: string;
  duration: DurationModel;
  terrainIds: string[];
  studyIds: string[];
  adminIds: string[];
  tasks: PlaybookTask[];
}

