/** Trame du projet, résolue depuis le type enregistré (jamais devinée). */
export function playbookForCategory(category: string | null | undefined): ExecutionPlaybook {
  const raw = (category ?? "").trim();
  const resolved = resolveProjectType(raw) ?? (CATEGORY_TO_PLAYBOOK[raw.toLowerCase()] ? raw.toLowerCase() : null);
  const key = resolved ? CATEGORY_TO_PLAYBOOK[resolved] : undefined;
  return PLAYBOOKS[key ?? "generique"] ?? PLAYBOOKS.generique;
}

