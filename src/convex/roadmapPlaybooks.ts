// ----------------------------------------------------------------------------
// Chaque type de projet possède sa propre trame de chantier : phases réellement
// nécessaires, tâches, métiers, matériaux, contrôles et risques. Aucune trame
// n'est partagée entre deux familles de projets (une piscine n'a pas de
// charpente, une rénovation de salle de bain n'a pas de terrassement).
//
// Le moteur (`roadmapEngine`) ne fait que :
//   • résoudre le type enregistré du projet → trame ;
//   • filtrer les tâches conditionnelles (étages, piscine, extérieurs…) ;
//   • déplier les tâches « par niveau » avec les surfaces RÉELLES du projet ;
//   • répartir le budget et la durée de l'estimation sur ces tâches.
// Aucune quantité, surface ni montant n'est inventé ici.
// ============================================================================

