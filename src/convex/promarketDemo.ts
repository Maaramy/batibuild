/** Construit le document `promarketProfiles` d'une fiche de démonstration. */
export function buildDemoProfileDoc(seed: DemoProfessionalSeed, now: number) {
  const category = PROMARKET_CATEGORY_BY_TRADE[seed.trade] ?? "services";
  return {
    displayName: seed.name,
    companyName: seed.company,
    trade: seed.trade,
    category,
    kind: (seed.kind ?? "independant") as "independant" | "entreprise",
    description: seed.about,
    specialties: seed.specialties ?? [],
    services: seed.services,
    region: seed.region,
    city: seed.city,
    zones: seed.zones,
    phone: seed.phone,
    whatsapp: seed.phone,
    email: seed.email,
    experienceYears: seed.years,
    availability: seed.availability,
    urgent: seed.urgent ?? false,
    homeService: seed.home ?? false,
    priceFrom: seed.price,
    priceUnit: seed.unit,
    ratingSum: Math.round(seed.rating * seed.reviews * 10) / 10,
    ratingCount: seed.reviews,
    views: seed.reviews * 7,
    contacts: Math.round(seed.reviews / 2),
    quoteCount: Math.round(seed.reviews / 3),
    completedCount: Math.round(seed.reviews / 2),
    // Les badges de vérification restent ADMINISTRATIFS : les fiches de
    // démonstration n'en portent aucun, sauf le badge « Recommandé » qui est
    // explicitement un choix éditorial de la démo.
    verifiedIdentity: false,
    verifiedPro: false,
    verifiedDocs: false,
    recommended: seed.recommended ?? false,
    status: "active" as const,
    demo: true,
    createdAt: now,
    updatedAt: now,
  };
}

