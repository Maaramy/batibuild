// ============================================================================
// NOM AUTOMATIQUE DES PROJETS — « #N Mon/Ma <type de projet> »
//
// Logique PARTAGÉE entre le formulaire « Nouveau projet » (React) et le
// backend Convex : les deux DOIVENT produire exactement le même libellé, sinon
// le backend ne reconnaîtrait plus un nom encore automatique et écraserait une
// saisie manuelle (ou l'inverse : il conserverait un numéro provisoire).
//
//   • Le nom est construit en trois morceaux : «#N» (numéro séquentiel),
//     le déterminant (« Mon » / « Ma » selon le genre du nom en français),
//     puis le type de projet en minuscules : « #1 Ma maison ».
//   • Le déterminant est le SEUL élément qui ne peut pas être déduit
//     mécaniquement du type : il est donc déclaré explicitement pour les
//     21 types du catalogue officiel. Le nom, lui, est dérivé du libellé
//     officiel (PROJECT_TYPE_LABELS) pour rester synchrone avec le catalogue.
//   • Le numéro n'est JAMAIS codé en dur : il est calculé à partir du compteur
//     Convex (voir `allocateGeneratedProjectName` dans projects.ts), lui-même
//     initialisé depuis les projets déjà enregistrés.
// ============================================================================

import {
  PROJECT_TYPE_LABELS,
  projectTypeLabel,
  type ProjectType,
} from "./projectTypes";

export type ProjectNameArticle = "Mon" | "Ma";

/**
 * Déterminant du nom généré, par type de projet du catalogue officiel.
 * « Mon » devant un nom masculin OU commençant par une voyelle (mon extension,
 * mon électricité), « Ma » devant un nom féminin.
 */
export const PROJECT_NAME_ARTICLES: Record<ProjectType, ProjectNameArticle> = {
  maison: "Ma",
  villa: "Ma",
  appartement: "Mon",
  studio: "Mon",
  duplex: "Mon",
  immeuble: "Mon",
  local_commercial: "Mon",
  bureau: "Mon",
  entrepot: "Mon",
  residence_touristique: "Ma",
  projet_neuf: "Mon",
  renovation_complete: "Ma",
  extension_batiment: "Mon",
  renovation_cuisine: "Ma",
  renovation_salle_de_bain: "Ma",
  peinture_interieure: "Ma",
  piscine: "Ma",
  restaurant: "Mon",
  cafe: "Mon",
  electricite_complete: "Mon",
  plomberie_complete: "Ma",
};

/**
 * Noms de projet générables : libellés officiels en minuscules. Sert à
 * reconnaître un nom automatique (et donc à autoriser son actualisation) sans
 * jamais confondre avec un nom saisi par l'utilisateur.
 */
const GENERATED_NOUNS: Set<string> = new Set(
  Object.values(PROJECT_TYPE_LABELS).map((label) => label.toLowerCase()),
);

/** Nom du projet en minuscules pour un type donné (« rénovation cuisine »). */
export function projectNameNoun(category: string | null | undefined): string {
  return projectTypeLabel(String(category ?? "")).toLowerCase();
}

/** Déterminant (« Mon » / « Ma ») pour un type donné. */
export function projectNameArticle(category: string | null | undefined): ProjectNameArticle {
  return PROJECT_NAME_ARTICLES[category as ProjectType] ?? "Mon";
}

/**
 * Nom automatique complet : « #1 Ma maison ».
 * Le numéro est borné à un entier ≥ 1 (jamais « #0 » ni « #1.5 »).
 */
export function formatProjectName(
  category: string | null | undefined,
  number: number,
): string {
  const safe = Number.isFinite(number) ? Math.floor(number) : 1;
  const sequence = Math.max(1, safe);
  return `#${sequence} ${projectNameArticle(category)} ${projectNameNoun(category)}`;
}

/**
 * Décompose un nom automatique (« #12 Ma piscine ») en numéro / déterminant /
 * nom. Renvoie `null` dès qu'il ne s'agit pas d'un nom généré par
 * l'application : un nom saisi à la main n'est JAMAIS réécrit.
 */
export function parseAutoGeneratedProjectName(
  name: string | null | undefined,
): { number: number; article: ProjectNameArticle; noun: string } | null {
  const match = /^#(\d{1,7})\s+(Mon|Ma)\s+(.+)$/.exec(String(name ?? "").trim());
  if (!match) return null;

  const number = Number(match[1]);
  if (!Number.isInteger(number) || number < 1) return null;

  const noun = match[3].trim().toLowerCase();
  if (!GENERATED_NOUNS.has(noun)) return null;

  return { number, article: match[2] as ProjectNameArticle, noun };
}

/** Vrai si le nom est encore au format généré automatiquement. */
export function isAutoGeneratedProjectName(name: string | null | undefined): boolean {
  return parseAutoGeneratedProjectName(name) !== null;
}

/** Numéro extrait d'un nom généré, sinon `null`. */
export function projectNumberFromName(name: string | null | undefined): number | null {
  return parseAutoGeneratedProjectName(name)?.number ?? null;
}

/**
 * Prochain numéro calculé à partir des projets DÉJÀ enregistrés (le plus grand
 * numéro attribué + 1, donc jamais de réutilisation). Sert à initialiser le
 * compteur Convex quand il n'existe pas encore.
 */
export function nextProjectNumberFromNames(names: Iterable<string>): number {
  let max = 0;
  for (const name of names) {
    const number = projectNumberFromName(name);
    if (number !== null && number > max) max = number;
  }
  return max + 1;
}

export interface GeneratedNameInput {
  /** Valeur actuelle du champ « Nom du projet ». */
  current: string;
  /** Vrai dès que l'utilisateur a modifié le nom lui-même. */
  manuallyEdited: boolean;
  /** Type de projet sélectionné (aucun → champ laissé tel quel). */
  category: string | null | undefined;
  /** Numéro à utiliser (aperçu du compteur Convex). */
  number: number;
}

/**
 * Nom à afficher après une action de l'utilisateur (sélection d'un type,
 * effacement du champ, arrivée du compteur) :
 *
 *   • saisie manuelle (non vide) → conservée telle quelle ;
 *   • champ vide → (re)généré pour le type sélectionné ;
 *   • nom encore automatique → actualisé pour le nouveau type / numéro.
 */
export function resolveGeneratedProjectName({
  current,
  manuallyEdited,
  category,
  number,
}: GeneratedNameInput): string {
  if (!category) return current;

  const trimmed = current.trim();
  if (manuallyEdited && trimmed !== "") return current;
  if (trimmed !== "" && !isAutoGeneratedProjectName(trimmed)) return current;

  return formatProjectName(category, number);
}
