/**
 * Coefficients multi-niveaux configurés par l'administrateur (table
 * `bimConfig`). Une configuration absente ou illisible retombe sur les valeurs
 * par défaut : le calcul ne dépend jamais d'une donnée partiellement écrite.
 */
async function readLevelCostConfigFromDb(ctx: DbCtx): Promise<LevelCostConfig> {
  const config = await ctx.db.query("bimConfig").order("desc").first();
  return resolveLevelCostConfig(parseLevelCoefficients(config?.levelCoefficients));
}

/**
 * Surfaces couvertes réelles niveau par niveau d'un projet : la surface saisie
 * pour un niveau est conservée telle quelle ; un niveau non renseigné reprend
 * la surface du RDC.
 */
function normalizeLevelSurfacesInput(project: {
  surface?: number | null;
  floors?: number | null;
  levelSurfaces?: number[] | null;
}): number[] {
  return normalizeLevelSurfaces(
    project.surface ?? 150,
    project.floors ?? 1,
    project.levelSurfaces,
  );
}

