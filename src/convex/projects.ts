/** Generate a professional BIM analysis with Tunisian 2026 prices */
export const simulateAnalysis = mutation({
  args: { projectId: v.id("projects") },
  handler: async (ctx, args) => {
    const user = await getCurrentUser(ctx);
    if (!user) return;

    // Services Client Pro : abonnement payant actif requis
    await requireClientProAccess(ctx, user, "Estimation des coûts", "estimation");

    const project = await ctx.db.get(args.projectId);
    if (!project) return;

    const surface = project.surface ?? 150;
    // Nombre de niveaux effectif : valeur saisie par l'utilisateur si présente
    // (sélecteur manuel), sinon déduite du type de projet.
    const floors = project.floors ?? inferFloorsFromCategory(project.category);
    // Les types « Maison R+1 » / « Maison R+2 » ont été supprimés du catalogue :
    // les projets existants enregistrés avec ces anciens slugs sont
    // recalculés comme « maison » / « villa » avec leur nombre de niveaux.
    const category = normalizeLegacyCategory(project.category);
    const region = project.region ?? "tunis";
    const finishLevel = (project as any).finish_level || "standard";

    // Prix en direct depuis la base materialPrices (catalogue officiel 2026) :
    // les libellés, unités et prix unitaires du « Quantitatif détaillé » sont
    // résolus vers la base ; toute modification de prix faite dans le panneau
    // admin se reflète automatiquement dans les nouvelles estimations.
    const liveRows = await ctx.db.query("materialPrices").collect();
    const livePrices = buildLivePriceMap(
      liveRows.map((m) => ({ name: m.name, unit: m.unit, unitPrice: m.unitPrice })),
    );

    // ── Calcul multi-niveaux : coefficients & surfaces réelles par niveau ──
    // Les coefficients (RDC 100 % · R+1/R+2 65-80 % · R+3+ 56-80 %) proviennent
    // de la configuration administrateur quand elle existe, sinon des valeurs
    // par défaut de `lib/buildingLevels` : aucune modification du code source
    // n'est nécessaire pour les ajuster.
    const levelConfig = await readLevelCostConfigFromDb(ctx);
    const levelSurfaces = normalizeLevelSurfacesInput(project);
    // Taux de TVA du DQE de rénovation de salle de bain réglé par
    // l'administrateur (absent → 19 %, taux de droit commun).
    const sdbConfig = await ctx.db.query("bimConfig").order("desc").first();

    const result = withLivePrices(livePrices, () =>
      runBIMEstimation(category, surface, floors, region, finishLevel, {
        bedrooms: project.bedrooms,
        bathrooms: project.bathrooms,
        kitchens: project.kitchens,
        livingRooms: project.livingRooms,
        garages: project.garages,
        wcs: project.wcs,
        pools: project.pools,
      }, { levelSurfaces, levelConfig }),
    );

    // Portes & fenêtres du « Quantitatif détaillé » : quantités réalistes par
    // pièce (1 porte intérieure par pièce, 1-2 fenêtres par pièce, 2 portes
    // principales) selon le nombre de pièces du projet. Les prix unitaires du
    // catalogue 2026 / base materialPrices sont conservés ; l'écart de budget
    // de la catégorie « Second œuvre » est réparti sur les autres postes.
    // Les défauts pièces sont alignés sur ceux du moteur BIM (~1 pièce / 45 m²).
    // Surface réellement construite : somme des surfaces couvertes de CHAQUE
    // niveau (un étage plus petit que le RDC ne reçoit jamais la surface du RDC).
    const tb = realBuiltArea(surface, floors, levelSurfaces);
    result.costEstimate.breakdown = applyRealisticDoorsWindows(
      result.costEstimate.breakdown,
      {
        bedrooms: project.bedrooms ?? Math.max(1, Math.round(tb / 45)),
        bathrooms: project.bathrooms ?? Math.max(1, Math.round(tb / 80)),
        kitchens: project.kitchens ?? 1,
        livingRooms: project.livingRooms ?? Math.max(1, Math.round(tb / 75)),
        garages: project.garages ?? 0,
        wcs: project.wcs ?? Math.max(1, Math.round(tb / 90)),
        pools: project.pools ?? 0,
      },
    );

    // ── Devis Quantitatif Estimatif (DQE) ──
    // « Quantitatif détaillé » structuré selon le modèle Google Sheets de
    // référence : lots / sous-lots, désignation, description, unité, quantité,
    // prix unitaire, montant (Montant = Quantité × P.U.), sous-total par lot,
    // totaux par nature (matériaux, main-d'œuvre, équipements, transport,
    // études) et coût moyen au m². Le budget total clé en main (coût réel des
    // travaux, sans imprévus) est réparti par lot ; les prix en direct de la
    // base materialPrices
    // écrasent les prix de référence internes du moteur.
    // Coefficient régional appliqué aux postes à barème absolu du Quantitatif
    // détaillé (peinture au seau, plomberie et électricité au m²) : le barème
    // de base est national (Médenine = 100 %), il doit suivre la région du
    // projet comme le reste des lots. Une seule application, jamais cumulée.
    const technicalRegionFactor = regionCostFactor(
      REGION_COST_M2,
      region,
      "standard",
    );
    // Équipements sanitaires réellement déclarés sur le projet : ils adaptent
    // les quantités de plomberie / électricité du Quantitatif détaillé (règle
    // partagée `lib/dqeTechnicalLots`). Aucun champ renseigné → aucune
    // majoration : la quantité reste la surface construite.
    const hasRoomsInfo =
      project.bathrooms !== undefined ||
      project.kitchens !== undefined ||
      project.wcs !== undefined;
    const dqe = generateDqe({
      category,
      surface,
      floors,
      totalBudget: result.costEstimate.totalCost,
      livePrices,
      levelSurfaces,
      regionFactor: technicalRegionFactor,
      sdbVatRate: sdbConfig?.sdbVatRate,
      rooms: hasRoomsInfo
        ? {
            bathrooms: project.bathrooms,
            kitchens: project.kitchens,
            wcs: project.wcs,
          }
        : undefined,
    });

    // ── Évolution annuelle des coûts (barème administrateur) ──────────────
    // S'applique UNIQUEMENT au moment du calcul :
    //   • aucune estimation déjà calculée et enregistrée n'est modifiée par ce
    //     module (seul un nouveau calcul peut porter des taux) ;
    //   • le mécanisme inactif (administration) ne change AUCUN montant ;
    //   • un chiffrage déjà validé (`costEstimateValidatedAt`) n'est jamais
    //     majoré ;
    //   • chaque poste reçoit son propre facteur — aucune double application.
    // L'empreinte du barème (version, date, statut) accompagne le calcul pour
    // le détail affiché et les rapports PDF des NOUVEAUX projets.
    const costEvolution = await readCostEvolutionSettings(ctx);
    const evolution = applyCostEvolutionToEstimate({
      settings: costEvolution.settings,
      version: costEvolution.version,
      chiffrageValide: Boolean(project.costEstimateValidatedAt),
      costEstimate: result.costEstimate,
      dqe,
      aiAnalysis: result.aiAnalysis,
      builtSurface: tb,
    });

    // ── Coût global TTC : les lots contenant un poste au barème technique
    // (plomberie 94 DT/m², électricité 72 DT/m²) ainsi que le lot « Second
    // œuvre et finitions » du résidentiel sont facturés à la SOMME RÉELLE de
    // leurs postes. Les autres lots conservent leur sous-total, leurs quantités
    // et leurs prix unitaires (aucun prix redistribué). Chaque écart est imputé
    // à la catégorie de coût de SON lot, jamais à une autre.
    const gridTotal = result.costEstimate.totalCost;
    const dqeTotal = dqe.totals.total;
    const dqeCostM2 = dqe.totals.costPerM2;
    // Écarts de lots : sous-total réel − budget alloué (0 pour un lot calé).
    const lotDeltas = dqe.lots
      .map((lot) => ({
        id: lot.id,
        name: lot.name,
        delta: lot.subtotal - (lot.allocatedSubtotal ?? lot.subtotal),
      }))
      .filter((entry) => entry.delta !== 0);
    const deltaByCategory = new Map<string, number>();
    for (const entry of lotDeltas) {
      const category = categoryForLot(entry.id) ?? "second_oeuvre";
      deltaByCategory.set(category, (deltaByCategory.get(category) ?? 0) + entry.delta);
    }
    // Les scénarios Économique / Premium suivent le même rapport que le
    // scénario de référence : l'ordre des budgets reste inchangé.
    const scenarioRatio = gridTotal > 0 ? dqeTotal / gridTotal : 1;
    const alignScenario = (s: any) =>
      s
        ? {
            ...s,
            totalCost: Math.round((Number(s.totalCost) || 0) * scenarioRatio),
            costPerM2: Math.round((Number(s.costPerM2) || 0) * scenarioRatio),
          }
        : s;
    const budgetScenarios = result.costEstimate.budgetScenarios
      ? {
          economique: alignScenario(result.costEstimate.budgetScenarios.economique),
          standard: {
            ...result.costEstimate.budgetScenarios.standard,
            totalCost: dqeTotal,
            costPerM2: dqeCostM2,
          },
          premium: alignScenario(result.costEstimate.budgetScenarios.premium),
        }
      : result.costEstimate.budgetScenarios;

    // ── Vérification automatique « coût global = somme du DQE » ──
    // Le Quantitatif détaillé doit toujours retomber exactement sur le coût
    // estimatif. Toute incohérence est remontée (jamais masquée) et affichée
    // dans l'interface d'administration avec le détail du calcul.
    const levelBreakdown = result.costEstimate.levelBreakdown;
    if (levelBreakdown) {
      // Les écarts de lots sont des ajustements EXPLICITES : le total reste
      // exactement la somme des niveaux + toiture + ces ajustements (comptés
      // une seule fois, jamais noyés dans un niveau).
      levelBreakdown.total = dqeTotal;
      levelBreakdown.costPerM2Real = dqeCostM2;
      levelBreakdown.costAdjustments = [
        ...(levelBreakdown.costAdjustments ?? []),
        ...lotDeltas.map((entry) => ({
          label: `${entry.name} — somme réelle des postes`,
          amount: entry.delta,
        })),
      ];
      // Résidu d'arrondi de la ventilation par niveau lorsque le barème
      // d'évolution a été appliqué : l'invariant « total = Σ niveaux +
      // toiture + ajustements » reste EXACT, l'arrondi étant remonté comme un
      // ajustement explicite (jamais masqué).
      if (evolution.applied) {
        const parts =
          levelBreakdown.levels.reduce(
            (s: number, l: any) => s + (Number(l?.amount) || 0),
            0,
          ) +
          (Number(levelBreakdown.roof?.amount) || 0) +
          levelBreakdown.costAdjustments.reduce(
            (s: number, a: any) => s + (Number(a?.amount) || 0),
            0,
          );
        const residual = Math.round((levelBreakdown.total - parts) * 100) / 100;
        if (residual !== 0) {
          levelBreakdown.costAdjustments.push({
            label: "Évolution annuelle des coûts — ventilation par niveau (arrondis)",
            amount: residual,
          });
        }
      }
      const dqeAnomalies = checkDqeConsistency(
        dqeTotal,
        dqe.totals.total,
        dqe.lots.length,
      );
      levelBreakdown.anomalies = [...levelBreakdown.anomalies, ...dqeAnomalies];
    }

    // Generate AI provider recommendations
    const recommendations = generateProviderRecommendations(
      category,
      region,
      dqeTotal,
      surface,
      floors,
      finishLevel
    );

    // Attach registered suppliers to each provider recommendation
    const providerTypes = recommendations.providers.map((p: any) => p.type);
    const supplierMap = new Map<string, any[]>();

    // ── Fournisseurs inscrits recommandés ──
    // Contrôle CENTRALISÉ de visibilité : essai en cours, abonnement payant
    // actif ou offre gratuite administrable — et profil visible/valide. Une
    // période d'essai échue ou un abonnement impayé exclut le fournisseur.
    const now = Date.now();
    const free = await getFreePlanStatus(ctx);
    const allProfiles = await ctx.db.query("supplierProfiles").collect();
    const validProfiles: typeof allProfiles = [];
    for (const profile of allProfiles) {
      if (await isProfilePaymentActive(ctx, free.supplierFree, profile, now)) {
        validProfiles.push(profile);
      }
    }

    // Map registered suppliers to provider types via their specialties
    for (const profile of validProfiles) {
      // Determine which provider types this supplier matches
      const matchedTypes = new Set<string>();
      for (const specialty of profile.specialties) {
        const providerTypesForSpecialty =
          SPECIALTY_TO_PROVIDER_TYPE[specialty] || [];
        providerTypesForSpecialty.forEach((t: string) => matchedTypes.add(t));
      }

      // For each matched provider type that's in our recommendations, add this supplier
      for (const type of matchedTypes) {
        if (providerTypes.includes(type)) {
          const existing = supplierMap.get(type) || [];
          const supplierEntry = {
            id: `registered_${profile._id}`,
            name: profile.companyName,
            phone: profile.phone,
            email: profile.email || undefined,
            address: profile.address,
            website: profile.website || undefined,
            description:
              profile.description || `Fournisseur inscrit - ${profile.companyName}`,
            rating: 4.5,
          };
          // Avoid duplicates
          if (!existing.some((s: any) => s.id === supplierEntry.id)) {
            existing.push(supplierEntry);
          }
          supplierMap.set(type, existing);
        }
      }
    }

    const enhancedProviders = recommendations.providers.map((p: any) => ({
      ...p,
      suppliers: supplierMap.get(p.type) || [],
    }));

    recommendations.providers = enhancedProviders;

    // Cast BIM categories to the valid union type for Convex schema
    const costEstimate = {
      ...result.costEstimate,
      totalCost: dqeTotal,
      costPerSquareMeter: dqeCostM2,
      budgetScenarios,
      levelBreakdown,
      // Chaque écart est imputé à la catégorie de coût de son propre lot : les
      // autres catégories, leurs postes et leurs montants restent strictement
      // inchangés — la somme de la répartition retombe donc exactement sur le
      // nouveau total TTC, sans doublon.
      breakdown: result.costEstimate.breakdown.map((b: any) => ({
        ...b,
        estimatedCost:
          (Number(b.estimatedCost) || 0) + (deltaByCategory.get(b.category) ?? 0),
        category: b.category as typeof materialCategoryValidator.type,
      })),
      // Empreinte du barème d'évolution (version, date, statut) : affichée
      // dans le détail du calcul et reprise par les rapports PDF des nouveaux
      // projets. Absente → aucun taux n'a été appliqué à cette estimation.
      costEvolution: evolution.fingerprint,
    };

    await ctx.db.patch(args.projectId, {
      status: PROJECT_STATUS.COMPLETED,
      costEstimate,
      dqe: dqe as any,
      aiAnalysis: result.aiAnalysis,
      optimizationTips: result.optimizationTips,
      technicalRecommendations: result.technicalRecommendations,
      providerRecommendations: recommendations,
      updatedAt: Date.now(),
    });

    // ── Auto-lancement de « Choix matériaux AI » (§9) ──
    // Dès la fin du Coût estimatif, le module s'initialise à partir du
    // Quantitatif détaillé qui vient d'être calculé (scénario de référence +
    // sélection proposée par l'IA), SANS aucune redirection : l'utilisateur
    // reste là où il est. Best-effort : ne bloque jamais le calcul de coût.
    await autoLaunchMaterialSelection(ctx, user._id, args.projectId);
  },
});

