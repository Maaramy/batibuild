import { describe, expect, it } from "vitest";

import {
  PROJECT_NAME_ARTICLES,
  formatProjectName,
  isAutoGeneratedProjectName,
  nextProjectNumberFromNames,
  parseAutoGeneratedProjectName,
  projectNameArticle,
  projectNameNoun,
  projectNumberFromName,
  resolveGeneratedProjectName,
} from "./projectNaming";
import { PROJECT_TYPE_LABELS, PROJECT_TYPES } from "./projectTypes";

// ============================================================================
// RÈGLES DE NOMMAGE AUTOMATIQUE « #N Mon/Ma <type de projet> »
// ----------------------------------------------------------------------------
// Ces règles sont partagées par le formulaire « Nouveau projet » et le backend
// Convex : les deux doivent produire et reconnaître EXACTEMENT le même libellé,
// sinon un nom encore automatique serait pris pour une saisie manuelle (numéro
// provisoire conservé) ou l'inverse (nom de l'utilisateur écrasé).
// ============================================================================

describe("nom automatique des projets — format", () => {
  it("respecte les exemples officiels du catalogue", () => {
    // Le numéro est dynamique : les exemples de la spécification sont vérifiés
    // avec le numéro de leur position dans la liste (#1 … #14).
    const EXPECTED = [
      "maison",
      "villa",
      "appartement",
      "studio",
      "duplex",
      "immeuble",
      "local_commercial",
      "bureau",
      "entrepot",
      "residence_touristique",
      "projet_neuf",
      "renovation_cuisine",
      "renovation_salle_de_bain",
      "piscine",
    ].map((category, index) => formatProjectName(category, index + 1));

    expect(EXPECTED).toEqual([
      "#1 Ma maison",
      "#2 Ma villa",
      "#3 Mon appartement",
      "#4 Mon studio",
      "#5 Mon duplex",
      "#6 Mon immeuble",
      "#7 Mon local commercial",
      "#8 Mon bureau",
      "#9 Mon entrepôt",
      "#10 Ma résidence touristique",
      "#11 Mon projet immobilier neuf",
      "#12 Ma rénovation cuisine",
      "#13 Ma rénovation salle de bain",
      "#14 Ma piscine",
    ]);
  });

  it("couvre les 20 types du catalogue, avec un nom en minuscules", () => {
    for (const category of PROJECT_TYPES) {
      const name = formatProjectName(category, 1);
      const article = PROJECT_NAME_ARTICLES[category];
      expect(article, category).toMatch(/^(Mon|Ma)$/);
      expect(name, category).toBe(
        `#1 ${article} ${PROJECT_TYPE_LABELS[category].toLowerCase()}`,
      );
      // Numéro précédé de « # », déterminant capitalisé, nom en minuscules.
      expect(name, category).toMatch(/^#\d+ (Mon|Ma) [^A-ZÀ-Ý]/);
    }
  });

  it("ne produit jamais « #0 » ni un numéro fractionnaire", () => {
    expect(formatProjectName("maison", 0)).toBe("#1 Ma maison");
    expect(formatProjectName("maison", -4)).toBe("#1 Ma maison");
    expect(formatProjectName("maison", 3.7)).toBe("#3 Ma maison");
    expect(formatProjectName("maison", Number.NaN)).toBe("#1 Ma maison");
  });

  it("expose déterminant et nom pour un type, avec repli sûr", () => {
    expect(projectNameArticle("piscine")).toBe("Ma");
    expect(projectNameArticle("entrepot")).toBe("Mon");
    // Type inconnu : on ne casse pas la phrase (« Mon » devant voyelle incluse).
    expect(projectNameArticle("type_inconnu")).toBe("Mon");
    expect(projectNameNoun("renovation_cuisine")).toBe("rénovation cuisine");
  });
});

describe("reconnaissance d'un nom automatique", () => {
  it("reconnaît les noms générés et en extrait le numéro", () => {
    expect(parseAutoGeneratedProjectName("#12 Ma piscine")).toEqual({
      number: 12,
      article: "Ma",
      noun: "piscine",
    });
    expect(isAutoGeneratedProjectName("#7 Mon bureau")).toBe(true);
    expect(projectNumberFromName("#7 Mon bureau")).toBe(7);
    // Espaces parasites tolérés (copier/coller).
    expect(projectNumberFromName("  #42 Mon entrepôt  ")).toBe(42);
  });

  it("ne confond JAMAIS un nom saisi par l'utilisateur avec un nom généré", () => {
    const manual = [
      "Villa à Carthage",
      "Mon projet",
      "#1 Maison",
      "#1 Mon garage",
      "#1 Ma maison de rêve",
      "#1",
      "##1 Ma maison",
      "#0 Ma maison",
      "",
      "   ",
    ];
    for (const name of manual) {
      expect(isAutoGeneratedProjectName(name), `« ${name} »`).toBe(false);
      expect(projectNumberFromName(name), `« ${name} »`).toBeNull();
    }
  });
});

describe("numéro suivant calculé à partir des projets existants", () => {
  it("prend le plus grand numéro attribué + 1 (jamais de réutilisation)", () => {
    expect(nextProjectNumberFromNames([])).toBe(1);
    expect(
      nextProjectNumberFromNames([
        "Projet de construction",
        "#3 Ma maison",
        "#7 Mon bureau",
        "#5 Ma villa",
      ]),
    ).toBe(8);
    // Un nom manuel contenant un numéro ne fausse pas le calcul.
    expect(nextProjectNumberFromNames(["#9 Ma maison", "Immeuble #100"])).toBe(10);
  });
});

describe("mise à jour du nom selon les actions de l'utilisateur", () => {
  const refresh = (current: string, category: string, number: number, manuallyEdited = false) =>
    resolveGeneratedProjectName({ current, manuallyEdited, category, number });

  it("génère le nom quand le champ est vide et qu'un type est sélectionné", () => {
    expect(refresh("", "maison", 1)).toBe("#1 Ma maison");
    expect(refresh("   ", "bureau", 2)).toBe("#2 Mon bureau");
  });

  it("actualise le nom généré au changement de type", () => {
    expect(refresh("#1 Ma maison", "piscine", 3)).toBe("#3 Ma piscine");
    expect(refresh("#1 Ma maison", "villa", 1)).toBe("#1 Ma villa");
  });

  it("préserve une saisie manuelle, même après changement de type", () => {
    expect(refresh("Villa familiale à Sousse", "maison", 4, true)).toBe(
      "Villa familiale à Sousse",
    );
    expect(refresh("#1 Ma maison perso", "maison", 4, true)).toBe("#1 Ma maison perso");
  });

  it("autorise la régénération après un effacement manuel", () => {
    expect(refresh("", "maison", 4, false)).toBe("#4 Ma maison");
    expect(refresh("", "renovation_cuisine", 9, false)).toBe("#9 Ma rénovation cuisine");
  });

  it("ne touche à rien sans type de projet sélectionné", () => {
    expect(refresh("", "", 1)).toBe("");
    expect(refresh("Mon nom", "", 1)).toBe("Mon nom");
  });
});
